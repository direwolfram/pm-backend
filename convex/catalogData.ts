export const TARGET_SKU_COUNT = 1500;

export function expandCatalog(targetSkus: number = TARGET_SKU_COUNT): CatalogProduct[] {
  const products: CatalogProduct[] = [];
  let skuSeq = 0;
  let totalSkus = 0;
  outer: for (const family of FAMILIES) {
    const flavours = family.flavours && family.flavours.length > 0 ? family.flavours : [undefined];
    for (const flavour of flavours) {
      const name = flavour ? `${family.name} ${flavour}` : family.name;
      const skus: CatalogSku[] = family.variants.map(([label, price, compareAt]) => {
        skuSeq += 1;
        return {
          code: `PM-${String(skuSeq).padStart(4, "0")}`,
          label,
          price,
          compareAt,
        };
      });
      totalSkus += skus.length;
      products.push({
        brand: family.brand,
        name,
        cat: family.cat,
        emoji: family.emoji,
        color: family.color,
        tag: family.tag,
        flavour,
        zone: family.zone ?? "ambient",
        frequent: family.frequent ?? false,
        fresh: family.fresh ?? false,
        skus,
      });
      if (totalSkus >= targetSkus) break outer;
    }
  }
  return products;
}

export function catalogSlug(name: string): string {
  return slugify(name);
}
